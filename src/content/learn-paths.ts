// الدوال المساعدة
// ============================================
export function getAllLessons(): Array<Lesson & { pathId: string; pathTitle: string }> {
  const result: Array<Lesson & { pathId: string; pathTitle: string }> = [];
  LEARNING_PATHS.forEach(path => {
    path.lessons.forEach(lesson => {
      result.push({ ...lesson, pathId: path.id, pathTitle: path.title });
    });
  });
  return result;
}

export function findLesson(lessonId: string) {
  for (const path of LEARNING_PATHS) {
    const lesson = path.lessons.find(l => l.id === lessonId);
    if (lesson) return { lesson, path };
  }
  return null;
}

